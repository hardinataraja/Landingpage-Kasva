import { computeSubscription, addMonths } from '../api/_subscription.js';
let f=0; const ok=(c,n)=>{ if(!c){f++;console.log('FAIL',n)} else console.log('ok  ',n)};
const now = new Date('2026-11-02T10:00:00Z');
const m = { plan:'pro', billing:'monthly', months:1 };
const y = { plan:'pro', billing:'yearly', months:12 };
let r = computeSubscription(undefined, m, now);
ok(r.fields.expiredAt==='2026-12-02T10:00:00.000Z' && !r.extending && r.fields.startedAt===now.toISOString(),'baru → +1 bulan');
r = computeSubscription({plan:'pro',status:'active',expiredAt:'2026-11-20T00:00:00.000Z',startedAt:'2026-10-20T00:00:00.000Z'}, m, now);
ok(r.fields.expiredAt==='2026-12-20T00:00:00.000Z' && r.extending && !('startedAt' in r.fields),'perpanjang dari sisa masa aktif, startedAt dipertahankan');
r = computeSubscription({plan:'pro',status:'active',expiredAt:'2026-11-01T00:00:00.000Z'}, m, now);
ok(r.fields.expiredAt==='2026-12-02T10:00:00.000Z' && !r.extending,'sudah expired → mulai dari sekarang');
r = computeSubscription({plan:'pro',status:'expired',expiredAt:'2027-01-01T00:00:00.000Z'}, m, now);
ok(!r.extending,'status expired tidak dianggap aktif walau tanggal masa depan');
r = computeSubscription({plan:'pro',status:'active',expiredAt:{toDate:()=>new Date('2026-12-01T00:00:00Z')}}, y, now);
ok(r.fields.expiredAt==='2027-12-01T00:00:00.000Z' && r.extending,'Timestamp-like + tahunan');
